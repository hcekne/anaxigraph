"""Offline matched maintenance evidence; no model judgments or production service access.

Run: python benchmarks/semantic_maintenance.py --output benchmarks/results/<name>.json
Each version scans identical source states in its own process and temporary index. Semantic
facts are supplied by the fixture, not generated by a model. Tool timings exclude transport.
"""

